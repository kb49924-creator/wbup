def detect_gender(name: str, category: str = "", brand: str = "") -> str:
    """
    Определяет пол товара по названию, категории и бренду.
    Возвращает 'male', 'female' или 'unisex'.
    """
    if not name:
        return "unisex"

    text = name.lower()

    # 1. Явные слова в названии
    for kw in _MALE_KEYWORDS:
        if kw in text:
            return "male"
    for kw in _FEMALE_KEYWORDS:
        if kw in text:
            return "female"

    # 2. По категории
    if category in _FEMALE_CATEGORIES:
        return "female"
    if category in _MALE_CATEGORIES:
        return "male"

    # 3. По бренду/продавцу
    if brand in _FEMALE_BRANDS:
        return "female"
    if brand in _MALE_BRANDS:
        return "male"

    return "unisex"