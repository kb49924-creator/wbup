def detect_category(name: str) -> str:
    """
    Определяет красивое название категории
    по названию товара.
    """

    if not name:
        return "Товар"

    text = name.lower()

    for keyword, category in CATEGORY_MAP.items():

        if keyword in text:
            return category

    return "Товар"


